/** Draw text with top-left at (x,y). `scale` is pixels per font pixel. Returns width. */
export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, scale: number, color: string, shadow = true): number {
  const s = scale;
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const g = GLYPHS[ch] ?? GLYPHS['?'];
    for (let r = 0; r < 5; r++)
      for (let c = 0; c < 3; c++) {
        if (g[r][c] !== '#') continue;
        if (shadow) { ctx.fillStyle = '#06070d'; ctx.fillRect(cx + c * s + s, y + r * s + s, s, s); }
        ctx.fillStyle = color; ctx.fillRect(cx + c * s, y + r * s, s, s);
      }
    cx += 4 * s;
  }
  return cx - x;
}

export const textWidth = (text: string, scale: number): number => text.length * 4 * scale;
